import type { NextFunction, Request, Response } from 'express';
import z from 'zod';
import type { DatabaseClient } from '@/shared/helpers/database.helper.js';
import { STATUS_CODES } from '@/shared/constants/status-codes.js';

const answerSchema = z.object({
    quizId: z.string().trim().min(1).max(50),
    itemKey: z.string().trim().min(1).max(50),
    prompt: z.string().trim().min(1).max(200),
    correctAnswer: z.number().int(),
    givenAnswer: z.number().int(),
    timeMs: z.number().int().min(0).max(3_600_000),
    answeredAt: z.iso.datetime({ offset: true }),
});

export const ValidationSchema = {
    body: z.object({
        clientId: z.uuid(), // generated by the browser; retrying the same attempt is safe
        kind: z.enum(['practice', 'tournament']),
        mode: z.enum(['input', 'options', 'mixed']),
        startedAt: z.iso.datetime({ offset: true }),
        durationMs: z.number().int().min(0).max(86_400_000),
        answers: z.array(answerSchema).min(1).max(500),
    }),
};

export async function Controller(
    req: Request,
    res: Response,
    next: NextFunction,
    db: DatabaseClient,
) {
    const b = req.body as z.infer<typeof ValidationSchema.body>;
    const learnerId = req.user!.id;

    const correct = b.answers.filter((a) => a.givenAnswer === a.correctAnswer).length;
    const quizIds = [...new Set(b.answers.map((a) => a.quizId))];

    await db.begin();
    try {
        const attempt = await db.queryOne<{ id: string }>(
            `INSERT INTO attempts (learner_id, client_id, kind, mode, quiz_ids, total, correct, duration_ms, started_at)
             VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
             ON CONFLICT (learner_id, client_id) DO NOTHING
             RETURNING id`,
            [learnerId, b.clientId, b.kind, b.mode, quizIds, b.answers.length, correct, b.durationMs, b.startedAt],
        );

        // Already saved (a retry): succeed without duplicating answers.
        if (!attempt) {
            await db.rollback();
            return res.status(STATUS_CODES.OK).json({ saved: false, duplicate: true });
        }

        await db.queryAll(
            `INSERT INTO answers (attempt_id, learner_id, quiz_id, item_key, prompt, correct_answer, given_answer, is_correct, time_ms, answered_at)
             SELECT $1, $2, x.quiz_id, x.item_key, x.prompt, x.correct_answer, x.given_answer,
                    x.given_answer = x.correct_answer, x.time_ms, x.answered_at
             FROM jsonb_to_recordset($3::jsonb) AS x(
                 quiz_id text, item_key text, prompt text, correct_answer bigint,
                 given_answer bigint, time_ms int, answered_at timestamptz)`,
            [
                attempt.id,
                learnerId,
                JSON.stringify(
                    b.answers.map((a) => ({
                        quiz_id: a.quizId,
                        item_key: a.itemKey,
                        prompt: a.prompt,
                        correct_answer: a.correctAnswer,
                        given_answer: a.givenAnswer,
                        time_ms: a.timeMs,
                        answered_at: a.answeredAt,
                    })),
                ),
            ],
        );

        await db.commit();
        return res.status(STATUS_CODES.CREATED).json({
            saved: true,
            attempt: { id: attempt.id, total: b.answers.length, correct },
        });
    } catch (err) {
        await db.rollback();
        throw err;
    }
}
